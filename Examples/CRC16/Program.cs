using SATInterface;
using System.Text;

//This example model attempts to solve a custom CRC16-like algorithm
//created by the author. It demonstrates how SAT solvers can be used to
//tackle cryptographic problems. We should find 17 solutions, one of them
//should be "satinter".
//
//This example was adapted from a model graciously shared by DARKER

ReadOnlySpan<byte> input = [0x67, 0x6C, 0x73, 0x1, 0x6B, 0x14, 0x1C, 0xF3, 0x38, 0x48, 0x67, 0x8C, 0x15, 0x8C, 0xF2, 0x2F];
ReadOnlySpan<char> pPrefix = ['m', 'e', 's', 's'];

using var m = new Model(new Configuration { Verbosity = 0 });

var p = new UIntVar[16];
var t = Enumerable.Range(0, 17).Select(i => new UIntVar[16]).ToArray();

for (int i = 0; i < 16; i++)
{
    t[0][i] = m.AddUIntVar(0x7F);
    for (var j = 1; j < 17; j++)
        t[j][i] = m.AddUIntVar(0xFF);

    if (i < pPrefix.Length)
        p[i] = m.AddUIntConst(pPrefix[i]);
    else
    {
        p[i] = m.AddUIntVar('~');
        m.AddConstr((p[i] == 0x9) | (p[i] == 0xA) | (p[i] >= ' '));
    }
}

var cleartext = new UIntVar[8];
for (int i = 0; i < cleartext.Length; i++)
{
    cleartext[i] = m.AddUIntVar('z');
    m.AddConstr(cleartext[i] >= 'a');
}

{
    var j = new UIntVar[8];
    j[0] = cleartext[3] & 0x7;
    for (var i = 1; i < 8; i++)
        j[i] = (j[0] + i).ToUInt(m) & 0x7;

    for (var i = 0; i < 8; i++)
    {
        m.AddConstr(t[0][i] == m.ITE(m.LookUpTable(j[i], cleartext) == 0x0, m.AddUIntConst(0x11 + i), (m.LookUpTable(j[i], cleartext) + j[i]) & 0x7F));
        m.AddConstr(m.LookUpTable((j[i] + 0x8).ToUInt(m), t[0]) == ((m.LookUpTable((j[i] + 0x3).ToUInt(m) & 0x7, cleartext) ^ t[0][i]) & 0x7F));
    }
}

var pom = m.AddUIntConst(0x7FED);
for (var i = 0; i < 16; i++)
{
    var bo = m.LookUpTable((t[i][0xF - i] + i).ToUInt(m) & 0xF, t[i]);

    m.AddConstr(p[i] == (bo ^ m.AddUIntConst(input[i])));
    pom = (pom >> 8) ^ Tab2(pom & 0xFF) ^ Tab2(p[i]);
    pom = (pom >> 8) ^ Tab2(pom & 0xFF) ^ Tab2(bo);

    for (var j = 0; j < 16; j++)
        m.AddConstr(t[i + 1][j] == (((i & 0xF) == j) ? (pom & 0xFF) : t[i][j]));
}

var found = 0;
m.EnumerateSolutions(cleartext, () =>
{
    found++;

    var sb = new StringBuilder();
    foreach (var ch in cleartext)
    {
        if (ch.X == 0)
            break;

        sb.Append((char)ch.X);
    }

    Console.ForegroundColor = (sb.ToString() == "satinter" ? ConsoleColor.Green : ConsoleColor.White);
    Console.WriteLine($"{found}: {sb.ToString()}");
});

